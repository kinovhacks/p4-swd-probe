"""Generate an OpenOCD Tcl script that programs an image into AT32F405 flash.

OpenOCD's built-in flash driver does not recognize the AT32F405, so this
generator emits the register-level erase/program sequence used during
validation. The generated script sources nothing and embeds the image words,
so keep it private if the image is private.

Example:
    python3 tools/gen_at32f405_flash_cfg.py app.bin \
        --base 0x08004000 -o /tmp/at32f405_flash.cfg
    openocd -f openocd/p4-swd-probe.cfg -f openocd/at32f405.cfg \
        -f /tmp/at32f405_flash.cfg
"""
import argparse
import hashlib
import pathlib
import sys

FLASH_CTRL = 0x40023C10
FLASH_STS = 0x40023C0C
FLASH_ADDR = 0x40023C14
FLASH_KEY = 0x40023C04


def words(image):
    padded = image + b'\xff' * (-len(image) % 4)
    return [int.from_bytes(padded[i:i + 4], 'little')
            for i in range(0, len(padded), 4)]


def generate(image, base, sector_size, verify):
    data = pathlib.Path(image).read_bytes()
    if not data:
        raise SystemExit('error: image is empty')
    if sector_size % 4:
        raise SystemExit('error: sector size must be a multiple of 4')
    if base % 4 or base % sector_size:
        raise SystemExit('error: base must be aligned to the sector size')
    if base + len(data) > 0x100000000:
        raise SystemExit('error: image does not fit in the 32-bit address space')
    ws = words(data)
    sectors = (len(ws) * 4 + sector_size - 1) // sector_size
    sha = hashlib.sha256(data).hexdigest()
    out = []
    add = out.append
    add('# SPDX-License-Identifier: Apache-2.0')
    add('# Generated by tools/gen_at32f405_flash_cfg.py')
    add(f'# image: {pathlib.Path(image).name}')
    add(f'# base: 0x{base:08x}')
    add(f'# size: {len(data)} bytes, {sectors} sectors of {sector_size}')
    add(f'# sha256: {sha}')
    add('set gerr 0')
    add('proc sec_erase {addr} {')
    add('    for {set a 0} {$a < 4} {incr a} {')
    add('        if {[catch {')
    add(f'            mww 0x{FLASH_ADDR:08X} $addr')
    add(f'            mww 0x{FLASH_CTRL:08X} 0x42')
    add(f'            set sv [lindex [read_memory 0x{FLASH_STS:08X} 32 1] 0]')
    add('            set w 0')
    add('            while {[expr {$sv & 1}]} { incr w; '
        'if {$w > 1000} { error OBF_TIMEOUT }; '
        f'set sv [lindex [read_memory 0x{FLASH_STS:08X} 32 1] 0] }}')
    add(f'            mww 0x{FLASH_CTRL:08X} 0x00')
    add('        } err]} {')
    add('            echo "erase retry $a at $addr: $err"')
    add(f'            catch {{ mww 0x{FLASH_CTRL:08X} 0x00 }}')
    add('        } else { return }')
    add('    }')
    add('    error "erase failed at $addr"')
    add('}')
    add('init')
    add('halt')
    add('mww 0x%08X 0x45670123' % FLASH_KEY)
    add('mww 0x%08X 0xCDEF89AB' % FLASH_KEY)
    add('mww 0x%08X 0x14' % FLASH_STS)

    for sector in range(sectors - 1, -1, -1):
        addr = base + sector * sector_size
        first = sector * sector_size // 4
        last = min(first + sector_size // 4, len(ws))
        add(f'echo "sector 0x{addr:08x}"')
        add(f'sec_erase 0x{addr:08x}')
        add(f'mww 0x{FLASH_CTRL:08X} 0x01')
        for i in range(first, last):
            a = base + i * 4
            add(f'if {{[catch {{mww 0x{a:08x} 0x{ws[i]:08x}}} e]}} '
                f'{{incr ::gerr; echo "wfail 0x{a:08x}: $e"}}')
        add(f'mww 0x{FLASH_CTRL:08X} 0x00')
        add(f'set sv [lindex [read_memory 0x{FLASH_STS:08X} 32 1] 0]')
        add(f'echo "sector 0x{addr:08x} done errors=$::gerr sts=$sv"')

    add('mww 0x%08X 0x80' % FLASH_CTRL)
    if verify:
        add(f'if {{[catch {{verify_image {{{pathlib.Path(image).resolve()}}} '
            f'0x{base:08x} bin}} e]}} '
            f'{{incr ::gerr; echo "verify failed: $e"}}')
    add('if {$::gerr} {')
    add('    echo "FAILED: $::gerr errors"')
    add('    shutdown')
    add('    error "flash write or verify failed"')
    add('}')
    add('echo "OK: all sectors written and verified"')
    add('resume')
    add('shutdown')
    return '\n'.join(out) + '\n'


def main():
    a = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    a.add_argument('image', help='binary image to program')
    a.add_argument('--base', type=lambda s: int(s, 0), default=0x08004000,
                   help='flash base address (default: 0x08004000)')
    a.add_argument('--sector-size', type=lambda s: int(s, 0), default=2048,
                   help='flash sector size in bytes (default: 2048)')
    a.add_argument('--no-verify', action='store_true',
                   help='skip the verify_image step after programming')
    a.add_argument('-o', '--output', required=True,
                   help='output OpenOCD script')
    args = a.parse_args()
    text = generate(args.image, args.base, args.sector_size,
                    not args.no_verify)
    pathlib.Path(args.output).write_text(text)
    print(f'wrote {args.output} ({len(text)} bytes)', file=sys.stderr)


if __name__ == '__main__':
    main()
